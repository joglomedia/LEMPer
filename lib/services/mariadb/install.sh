##
# Write a resource-profile tuning drop-in for MariaDB.
##
function tune_mariadb_config() {
    local PROFILE
    PROFILE=$(detect_resource_profile)

    local BUFFER_POOL MAX_CONNECTIONS TABLE_CACHE PERF_SCHEMA
    read -r BUFFER_POOL MAX_CONNECTIONS TABLE_CACHE PERF_SCHEMA <<< \
        "$(calc_mariadb_sizing "${PROFILE}")"

    local TUNING_FILE="/etc/mysql/mariadb.conf.d/99-lemper-tuning.cnf"

    run touch "${TUNING_FILE}"
    cat >"${TUNING_FILE}" <<EOL
# Generated by LEMPer for the '${PROFILE}' resource profile.
# Change SERVER_PROFILE in .env and re-run the installer to regenerate.
[mysqld]
innodb_buffer_pool_size = ${BUFFER_POOL}M
max_connections = ${MAX_CONNECTIONS}
table_open_cache = ${TABLE_CACHE}
performance_schema = ${PERF_SCHEMA}
EOL
    run chmod 0644 "${TUNING_FILE}"

    info "Applied MariaDB '${PROFILE}' resource profile."
}

##
# Add MariaDB Repository.
##
function add_mariadb_repo() {
    local version distro="${DISTRIB_NAME:-}" release="${RELEASE_NAME:-}"
    local root="${LEMPER_APT_ROOT:-/etc/apt}" key repo mirror="${MYSQL_REPO_MIRROR_URL:-}"
    lemper_load_module services/mariadb/repository || return 1
    version=$(lemper_mariadb_default_version "$distro" "$release" "${MYSQL_VERSION:-auto}") || return 1
    [[ "$version" =~ ^[0-9]+\.[0-9]+(\.[0-9]+)?$ && "$release" =~ ^[a-z]+$ ]] || {
        error "Invalid MariaDB repository version/codename."
        return 1
    }
    case "$distro" in debian | ubuntu) ;; *)
        error "Unsupported MariaDB distribution."
        return 1
        ;;
    esac
    if [[ "$distro/$release" == ubuntu/resolute ]]; then
        [[ -z "$mirror" ]] || {
            error "Resolute uses distribution MariaDB packages; reconcile the custom mirror first."
            return 1
        }
        lemper_mariadb_prepare_native "$version"
        return $?
    fi
    case "$release" in jessie) version=10.5 ;; bionic) version=11.4 ;; esac
    key="$root/keyrings/mariadb.gpg"
    lemper_load_module services/apt/repositories || return 1
    # Keep the upstream keyring checksum verification; no downloaded helper executes.
    lemper_apt_install_key https://supplychain.mariadb.com/mariadb-keyring-2019.gpg "$key" "" \
        https://supplychain.mariadb.com/mariadb-keyring-2019.gpg.sha256 || return 1
    if [[ -n "$mirror" ]]; then
        [[ "$mirror" =~ ^https?://[A-Za-z0-9.-]+(:[0-9]+)?(/[A-Za-z0-9_./-]*)?$ ]] || {
            error "MariaDB mirror must be an HTTP(S) URL without shell/query characters."
            return 1
        }
        repo="${mirror%/}/repo/$version/$distro"
    else
        repo="https://deb.mariadb.org/$version/$distro"
    fi
    lemper_apt_scope_sources mariadb "$key" || return 1
    # Preserve pre-existing repository choices and other entries in the helper's file.
    if ! lemper_apt_has_source mariadb; then
        lemper_apt_write_source "$root/sources.list.d/lemper-mariadb.list" \
            "deb [signed-by=$key] $repo $release main" || return 1
    fi
    local legacy
    for legacy in "$root/trusted.gpg.d/mariadb-keyring-2019.gpg" "$root/trusted.gpg.d/mariadb.gpg"; do
        lemper_apt_retire_key "$legacy" "$key" || return 1
    done
    lemper_exec apt-get update --allow-releaseinfo-change -q -y
}

##
# Install MariaDB (MySQL drop-in).
##
function init_mariadb_install() {
    if [[ "${AUTO_INSTALL}" == true ]]; then
        if [[ "${INSTALL_MYSQL}" == true ]]; then
            DO_INSTALL_MYSQL="y"
        else
            DO_INSTALL_MYSQL="n"
        fi
    else
        while [[ "${DO_INSTALL_MYSQL}" != y* && "${DO_INSTALL_MYSQL}" != n* ]]; do
            read -rp "Do you want to install MariaDB server? [y/n]: " -i y -e DO_INSTALL_MYSQL
        done
    fi

    # Do MariaDB server installation here...
    if [[ ${DO_INSTALL_MYSQL} == y* || ${DO_INSTALL_MYSQL} == Y* ]]; then
        # Add repository.
        add_mariadb_repo || return $?

        echo "Installing MariaDB (MySQL drop-in replacement) server..."

        # Install MariaDB
        local MARIADB_INSTALL_PACKAGES=()
        mapfile -t MARIADB_INSTALL_PACKAGES < <(lemper_mariadb_install_packages)
        run_spinner "Installing MariaDB" apt-get install -q -y "${MARIADB_INSTALL_PACKAGES[@]}"

        # Configure MySQL installation.
        if [[ "${DRYRUN}" == true ]]; then
            info "MariaDB server installed in dry run mode."
        else
            if [[ -n $(command -v mysql) ]]; then
                if [[ ! -d /etc/mysql/conf.d ]]; then
                    run mkdir -p /etc/mysql/conf.d
                    run cp -fr etc/mysql/conf.d /etc/mysql/
                fi

                if [[ ! -d /etc/mysql/mariadb.conf.d ]]; then
                    run mkdir -p /etc/mysql/mariadb.conf.d
                    run cp -fr etc/mysql/mariadb.conf.d /etc/mysql/
                fi

                [[ ! -f /etc/mysql/mariadb.cnf ]] && run cp -f etc/mysql/mariadb.cnf /etc/mysql/
                [[ ! -f /etc/mysql/my.cnf ]] && run ln -s /etc/mysql/mariadb.cnf /etc/mysql/my.cnf
                [[ ! -f /etc/mysql/debian.cnf ]] && run cp -f etc/mysql/debian.cnf /etc/mysql/

                # Debian start service.
                if [[ "${DISTRIB_NAME}/${RELEASE_NAME}" != ubuntu/resolute &&
                    (! -f /etc/mysql/debian-start || "${MYSQL_SECURE_INSTALL}" == true) ]]; then
                    run cp -f etc/mysql/debian-start /etc/mysql/
                    run chmod ugo+x /etc/mysql/debian-start
                fi

                # MySQL init script.
                if [[ ! -f /etc/init.d/mysql ]]; then
                    run cp etc/init.d/mysql /etc/init.d/
                    run chmod ugo+x /etc/init.d/mysql
                fi

                # MariaDB init script.
                if [[ ! -f /etc/init.d/mariadb ]]; then
                    run cp etc/init.d/mariadb /etc/init.d/
                    run chmod ugo+x /etc/init.d/mariadb
                fi

                # Systemd script.
                [[ ! -f /lib/systemd/system/mariadb.service ]] \
                    && run cp etc/systemd/mariadb.service /lib/systemd/system/

                [[ ! -f /etc/systemd/system/multi-user.target.wants/mariadb.service && -f /lib/systemd/system/mariadb.service ]] \
                    && run ln -sf /lib/systemd/system/mariadb.service /etc/systemd/system/multi-user.target.wants/mariadb.service

                [[ ! -f /etc/systemd/system/mysqld.service && -f /lib/systemd/system/mariadb.service ]] \
                    && run ln -sf /lib/systemd/system/mariadb.service /etc/systemd/system/mysqld.service

                [[ ! -f /etc/systemd/system/mysql.service && -f /lib/systemd/system/mariadb.service ]] \
                    && run ln -sf /lib/systemd/system/mariadb.service /etc/systemd/system/mysql.service

                # Size the server from the detected resources before first boot.
                tune_mariadb_config

                # Install default table.
                if [[ -n $(command -v mariadb-install-db) ]]; then
                    run mariadb-install-db --user=mysql
                elif [[ -n $(command -v mysql_install_db) ]]; then
                    run mysql_install_db --user=mysql
                else
                    error "Unable to secure MariaDB installation."
                fi

                # Trying to reload daemon.
                run systemctl daemon-reload

                # Unmask systemd service (?)
                run systemctl unmask mariadb.service

                # Enable MariaDB on startup.
                run systemctl enable mariadb.service

                # Restart MariaDB service daemon.
                run systemctl start mariadb.service

                ##
                # MariaDB secure installation
                # Ref: https://mariadb.com/kb/en/library/security-of-mariadb-root-account/
                #
                if [[ "${AUTO_INSTALL}" == true ]]; then
                    if [[ "${MYSQL_SECURE_INSTALL}" == true ]]; then
                        echo "Securing MariaDB Installation..."

                        # Ref: https://bertvv.github.io/notes-to-self/2015/11/16/automating-mysql_secure_installation/
                        MYSQL_ROOT_PASSWORD=${MYSQL_ROOT_PASSWORD:-$(openssl rand -hex 24)} || return 1
                        [[ -n "$MYSQL_ROOT_PASSWORD" ]] || {
                            error "Unable to generate MariaDB root credentials."
                            return 1
                        }
                        lemper_load_module services/mariadb/backup || return 1
                        lemper_load_module services/mariadb/database || return 1
                        lemper_mariabackup_secret_valid "$MYSQL_ROOT_PASSWORD" || {
                            error "Invalid MariaDB root credentials."
                            return 1
                        }
                        if [[ -z "${LEMPER_MARIADB_PROFILE:-}" && ! -f /etc/lemper/lemper.conf ]]; then
                            core_init_config || return 1
                        fi
                        lemper_mariadb_store_root_credential || return 1
                        local SQL_QUERY=""

                        # Setting the database root password.
                        SQL_QUERY="SET SESSION sql_mode='NO_BACKSLASH_ESCAPES';
                                ALTER USER 'root'@'localhost' IDENTIFIED BY $(lemper_db_password_sql "$MYSQL_ROOT_PASSWORD");"

                        # Delete anonymous users.
                        SQL_QUERY="${SQL_QUERY}
                                DELETE FROM mysql.user WHERE User='';"

                        # Ensure the root user can not log in remotely.
                        SQL_QUERY="${SQL_QUERY}
                                DELETE FROM mysql.user WHERE User='root' AND Host NOT IN ('localhost', '127.0.0.1', '::1');"

                        # Remove the test database.
                        SQL_QUERY="${SQL_QUERY}
                                DROP DATABASE IF EXISTS test;
                                DELETE FROM mysql.db WHERE Db='test' OR Db='test\_%';"

                        # Flush the privileges tables.
                        SQL_QUERY="${SQL_QUERY}
                                FLUSH PRIVILEGES;"

                        # Root password is blank for newly installed MariaDB (MySQL).
                        # Feed the statements via stdin so credentials stay out of argv.
                        if printf '%s\n' "${SQL_QUERY}" | MYSQL_PWD="${MYSQL_ROOT_PASSWORD}" mariadb --user=root >/dev/null 2>&1; then
                            success "Securing MariaDB server installation has been done."
                        else
                            error "Unable to secure MariaDB server installation."
                            return 1
                        fi
                    fi
                else
                    if [[ "${MYSQL_SECURE_INSTALL}" == true ]]; then
                        while [[ "${DO_MYSQL_SECURE_INSTALL}" != "y" && "${DO_MYSQL_SECURE_INSTALL}" != "n" ]]; do
                            read -rp "Do you want to secure MariaDB installation? [y/n]: " -e DO_MYSQL_SECURE_INSTALL
                        done

                        if [[ "${DO_MYSQL_SECURE_INSTALL}" == y* || "${DO_MYSQL_SECURE_INSTALL}" == Y* ]]; then
                            if [[ -n $(command -v mariadb-secure-installation) ]]; then
                                run mariadb-secure-installation
                            elif [[ -n $(command -v mysql_secure_installation) ]]; then
                                run mysql_secure_installation
                            else
                                error "Unable to secure MariaDB installation."
                            fi
                        fi
                    fi
                fi
            fi

            if [[ $(pgrep -c mariadb) -gt 0 || -n $(command -v mysql) ]]; then
                success "MariaDB server installed successfully."

                # Allow remote client access
                allow_remote_client_access

                # Enable Mariabackup
                enable_mariabackup || return 1

                # Restart MariaDB (MySQL)
                run systemctl restart mariadb.service

                if [[ $(pgrep -c mariadb) -gt 0 ]]; then
                    success "MariaDB server configured successfully."
                elif [[ -n $(command -v mysql) || -n $(command -v mariadb) ]]; then
                    # Server died? try to start it.
                    run systemctl start mariadb.service

                    if [[ $(pgrep -c mariadb) -gt 0 ]]; then
                        success "MariaDB server configured successfully."
                    else
                        info "Something went wrong with MariaDB server configuration."
                    fi
                fi
            else
                info "Something went wrong with MariaDB server installation."
            fi
        fi
    else
        info "MariaDB installation skipped."
    fi
}

##
# Enable MariaDB Backup tool.
##
function enable_mariabackup() {
    if [[ "${DRYRUN:-false}" != true && -z "${LEMPER_MARIADB_PROFILE:-}" && ! -f /etc/lemper/lemper.conf ]]; then
        core_init_config || return 1
    fi
    lemper_load_module services/mariadb/backup || return 1
    lemper_mariabackup_provision
}

##
# Allow remote client access
# You need to add the following query to the client account
#CREATE USER 'username'@'ip_address' IDENTIFIED BY 'secret';
#GRANT ALL PRIVILEGES ON *.* TO 'username'@'ip_address' WITH GRANT OPTION;
#CREATE USER 'username'@'%' IDENTIFIED BY 'secret';
#GRANT ALL PRIVILEGES ON *.* TO 'usernemae'@'%' WITH GRANT OPTION;
#FLUSH PRIVILEGES;
##
function allow_remote_client_access() {
    if [[ "${AUTO_INSTALL}" == true ]]; then
        if "${MYSQL_ALLOW_REMOTE}"; then
            ENABLE_REMOTE_ACCESS="y"
        else
            ENABLE_REMOTE_ACCESS="n"
        fi
    else
        while [[ "${ENABLE_REMOTE_ACCESS}" != "y" && "${ENABLE_REMOTE_ACCESS}" != "n" ]]; do
            read -rp "Do you want to allow MySQL remote client access? [y/n]: " -e ENABLE_REMOTE_ACCESS
        done
    fi

    if [[ ${ENABLE_REMOTE_ACCESS} == y* ]]; then
        REMOTE_CLIENT_CNF="###################################
# Custom optimization for LEMPer
# Allow remote client access
#
[mysqld]
skip-networking=0
skip-bind-address"

        if [[ -d /etc/mysql/mariadb.conf.d ]]; then
            run touch /etc/mysql/mariadb.conf.d/20-allow-remote-client-access.cnf
            run bash -c "echo '${REMOTE_CLIENT_CNF}' > /etc/mysql/mariadb.conf.d/20-allow-remote-client-access.cnf"
        else
            run bash -c "echo -e '\n${REMOTE_CLIENT_CNF}' >> /etc/mysql/my.cnf"
        fi
    fi
}

function lemper_mariadb_install_entry() {
    echo "[MariaDB (MySQL drop-in replacement) Installation]"
    if [[ -n $(command -v mariadb) && -n $(command -v mariadbd) && "${FORCE_INSTALL}" != true ]]; then
        info "MariaDB server already exists; reconciling backup configuration."
        if [[ "${INSTALL_MYSQL:-false}" == true ]]; then
            enable_mariabackup || return 1
        fi
    else
        init_mariadb_install "$@"
    fi
}
