#!/usr/bin/env bash

# Install ModSecurity v3 WAF
# Min. Requirement  : GNU/Linux Ubuntu/Debian
# Since Version     : 3.4.0

# Include helper functions.
if [[ "$(type -t run)" != "function" ]]; then
    BASE_DIR=$( cd "$( dirname "${BASH_SOURCE[0]}" )" >/dev/null 2>&1 && pwd )
    # shellcheck disable=SC1091
    . "${BASE_DIR}/utils.sh"

    # Make sure only root can run this installer script.
    requires_root "$@"

    # Make sure only supported distribution can run this installer script.
    preflight_system_check
fi

##
# Install ModSecurity v3 WAF and OWASP CRS.
##
function init_modsec_install() {
    if [[ "${AUTO_INSTALL}" == true ]]; then
        if [[ "${INSTALL_MODSEC}" == true ]]; then
            DO_INSTALL_MODSEC="y"
        else
            DO_INSTALL_MODSEC="n"
        fi
    else
        while [[ "${DO_INSTALL_MODSEC}" != "y" && "${DO_INSTALL_MODSEC}" != "Y" && \
            "${DO_INSTALL_MODSEC}" != "n" && "${DO_INSTALL_MODSEC}" != "N" ]]; do
            read -rp "Do you want to install ModSecurity v3 WAF? [y/n]: " -e DO_INSTALL_MODSEC
        done
    fi

    if [[ ${DO_INSTALL_MODSEC} == y* || ${DO_INSTALL_MODSEC} == Y* ]]; then
        echo "Installing ModSecurity v3 WAF..."

        # Install ModSecurity library and nginx connector module.
        if [[ "${DISTRIB_NAME}" == "ubuntu" ]] || [[ "${DISTRIB_NAME}" == "debian" ]]; then
            run apt-get install -q -y libmodsecurity3 nginx-mod-http-modsecurity
        else
            fail "ModSecurity installation is not supported on ${DISTRIB_NAME^}."
        fi

        # Install OWASP Core Rule Set (CRS).
        echo "Installing OWASP Core Rule Set..."

        local CRS_DIR="/usr/share/modsecurity-crs"

        if [[ ! -d "${CRS_DIR}" ]]; then
            # Clone CRS from GitHub.
            local CRS_VERSION="${MODSEC_CRS_VERSION:-"v3.3.5"}"
            run_spinner "Downloading OWASP CRS" git clone --depth 1 --branch "${CRS_VERSION}" \
                "https://github.com/coreruleset/coreruleset.git" "${CRS_DIR}"
        fi

        if [[ "${DRYRUN}" != true ]]; then
            # Create ModSecurity configuration directory.
            run mkdir -p /etc/modsecurity

            # Write main ModSecurity configuration.
            cat > /etc/modsecurity/modsecurity.conf <<EOL
# ModSecurity v3 Main Configuration
# Generated by LEMPer Stack

# Include the recommended ModSecurity core configuration.
Include /usr/share/modsecurity-crs/crs-setup.conf

# Include the OWASP CRS rules (enabled by default).
Include /usr/share/modsecurity-crs/rules/*.conf

# ModSecurity engine in detection-only mode by default.
# Set to "On" to enable blocking mode.
SecRuleEngine DetectionOnly

# Request body access for POST inspection.
SecRequestBodyAccess On

# Response body access for sensitive data leakage checks.
SecResponseBodyAccess On

# Maximum request body size (matches nginx client_max_body_size).
SecRequestBodyLimit {@SEC_BODY_LIMIT}

# Log format.
SecAuditLogRelevantStatus "^(?:5|4(?!03|04))"
SecAuditLogParts ABIJDEFHZ
EOL

            # Create nginx connector configuration.
            cat > /etc/modsecurity/modsecurity.conf.test <<'EOL'
# ModSecurity test configuration
# This file is loaded by the nginx connector.

# Include the main ModSecurity config.
Include /etc/modsecurity/modsecurity.conf
EOL

            # Create nginx include for ModSecurity activation.
            cat > "${BASE_DIR}/etc/nginx/includes/modsec.conf" <<'EOL'
## ModSecurity v3 WAF include.
# Include in server{} block to enable WAF for a vhost.

modsecurity on;
modsecurity_rules_file /etc/modsecurity/modsecurity.conf;
EOL

            # Enable the WAF nginx module.
            local modsec_module_link="/etc/nginx/modules-enabled/mod-http-modsecurity.conf"
            if [[ ! -f "${modsec_module_link}" ]]; then
                run ln -sf /usr/share/modsecurity/modsecurity.conf "${modsec_module_link}"
            fi

            success "ModSecurity v3 WAF installed with OWASP CRS."
            info "ModSecurity is in DetectionOnly mode by default."
            info "To enable blocking mode, edit /etc/modsecurity/modsecurity.conf"
            info "  and change 'SecRuleEngine DetectionOnly' to 'SecRuleEngine On'"
        else
            info "ModSecurity installed in dry run mode."
        fi
    else
        info "ModSecurity installation skipped."
    fi
}

echo "[ModSecurity v3 Installation]"

# Start running things from a call at the end so if this script is executed
# after a partial download it doesn't do anything.
if [[ -n $(command -v modsecurity) && "${FORCE_INSTALL}" != true ]]; then
    info "ModSecurity already exists, installation skipped."
else
    init_modsec_install "$@"
fi
